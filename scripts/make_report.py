"""Collect QC, benchmark and prioritization numbers into one Markdown summary."""
import argparse
import gzip
import json

import pandas as pd


def md_table(df):
    """Minimal Markdown table (avoids the optional 'tabulate' dependency)."""
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for row in df.itertuples(index=False):
        lines.append("| " + " | ".join("" if pd.isna(v) else str(v) for v in row) + " |")
    return "\n".join(lines)


def qc_numbers(a):
    fp = json.load(open(a.fastp))["summary"]
    flag = open(a.flagstat).read().splitlines()
    mapped = next(l for l in flag if "mapped (" in l and "primary" in l).split("(")[1].split()[0]
    paired = next(l for l in flag if "properly paired" in l).split("(")[1].split()[0]
    depth = pd.read_csv(a.depth, sep="\t")
    mean = depth.loc[depth["chrom"] == "total_region", "mean"].iloc[0]
    # thresholds file: bases covered at >=10x/20x/30x per region interval
    with gzip.open(a.thresholds, "rt") as fh:
        th = pd.read_csv(fh, sep="\t")
    length = (th["end"] - th["start"]).sum()
    cov = {c: th[c].sum() / length for c in ["10X", "20X", "30X"]}
    dup = next((l for l in open(a.markdup) if l.startswith("DUPLICATE TOTAL")), "0").split(":")[-1].strip()
    examined = next((l for l in open(a.markdup) if l.startswith("READ:")), "1").split(":")[-1].strip()
    return [
        ("read pairs (after extraction)", f"{fp['before_filtering']['total_reads'] // 2:,}"),
        ("reads passing fastp", f"{fp['after_filtering']['total_reads'] / fp['before_filtering']['total_reads']:.2%}"),
        ("Q30 bases (after fastp)", f"{fp['after_filtering']['q30_rate']:.2%}"),
        ("mapped (primary)", mapped),
        ("properly paired", paired),
        ("duplicate reads", f"{int(dup) / max(int(examined), 1):.2%}"),
        ("mean depth in region", f"{mean:.1f}x"),
        ("bases >=10x / >=20x / >=30x", " / ".join(f"{v:.1%}" for v in cov.values())),
    ]


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    for arg in ["region", "benchmark", "errors", "prioritized", "funnel", "fastp", "flagstat",
                "depth", "thresholds", "markdup", "out"]:
        ap.add_argument(f"--{arg}", required=True)
    a = ap.parse_args()

    bench = pd.read_csv(a.benchmark, sep="\t")
    bench = bench.sort_values(["filter_mode", "variant_class", "caller"], ascending=[False, False, False])
    for c in ["precision", "recall", "F1"]:
        bench[c] = bench[c].map("{:.4f}".format)
    errors = pd.read_csv(a.errors, sep="\t")
    rep = errors[errors["stratum"] == "tandem_repeat_or_homopolymer"].copy()
    rep["recall"] = rep["recall"].map("{:.4f}".format)
    prio = pd.read_csv(a.prioritized, sep="\t")
    funnel = pd.read_csv(a.funnel, sep="\t")

    out = [f"# Run summary: HG002, {a.region}", "",
           "Auto-generated by `scripts/make_report.py`. Research/demonstration use only.", "",
           "## Read and alignment QC", "", md_table(pd.DataFrame(qc_numbers(a), columns=["metric", "value"])), "",
           "## Benchmark vs GIAB v4.2.1 (high-confidence regions)", "",
           "`pass` = hard-filtered PASS calls, `all` = every call ignoring FILTER.", "",
           md_table(bench[["caller", "filter_mode", "variant_class", "truth_total", "TP_baseline",
                           "FP", "FN", "precision", "recall", "F1"]]), "",
           "### Recall inside vs outside tandem repeats / homopolymers (PASS)", "",
           md_table(rep[["caller", "variant_class", "level", "truth_n", "recall", "FN", "FP"]]
                    .rename(columns={"level": "in_repeat"})), "",
           "## Prioritization funnel", "", md_table(funnel), "",
           "## Prioritized variants", "",
           "Not a clinical interpretation: ClinVar labels are shown as submitted, no ACMG classification is made.", ""]
    show = ["tier", "gene", "POS", "REF", "ALT", "GT", "worst_consequence", "protein_change",
            "clinvar_significance", "clinvar_stars", "gnomAD_max_AF", "GIAB_status", "difficult_region"]
    out.append(md_table(prio[show]) if not prio.empty else "_No variants passed all filters._")
    open(a.out, "w").write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
